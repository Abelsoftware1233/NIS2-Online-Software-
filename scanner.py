def scan_domain_advanced(domain, max_ports=1000, max_workers=50, timeout=1.5):
    """Geavanceerde scan met 1000+ poorten en threading"""
    from .database import is_internal_ip
    
    # DNS resolutie
    try:
        ip = socket.gethostbyname(domain)
    except:
        return {'success': False, 'error': 'DNS resolution failed'}
    
    # Check internal IP
    if is_internal_ip(ip):
        return {'success': False, 'error': 'Internal IP addresses are not allowed'}
    
    # Poort scan
    scanner = PortScanner(max_workers=max_workers, timeout=timeout)
    ports_to_scan = list(COMMON_PORTS.keys())[:max_ports]
    port_results = scanner.scan_ports(domain, ports_to_scan)
    
    # Extra checks
    ssl_info = {}
    if 443 in port_results and port_results[443]['open']:
        ssl_info = get_ssl_info(domain)
    
    headers_info = get_http_headers(domain)
    mx_records = get_dns_records(domain, 'MX')
    
    return {
        'success': True,
        'results': {
            'domain': domain,
            'ip': ip,
            'timestamp': datetime.now().isoformat(),
            'ports': port_results,
            'port_summary': scanner.get_summary(),
            'ssl': ssl_info,
            'headers': headers_info,
            'mail': {'mx_records': mx_records},
            'open_ports_count': scanner.get_summary()['open_count']
        }
    }


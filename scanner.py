# ==================== SCANNER CLASS ====================
class PortScanner:
    def __init__(self, max_workers=50, timeout=1.5):
        self.max_workers = max_workers
        self.timeout = timeout
        self.results = {}
        
    def scan_port(self, host, port):
        """Scan een enkele poort"""
        try:
            sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            sock.settimeout(self.timeout)
            result = sock.connect_ex((host, port))
            sock.close()
            return port, result == 0
        except:
            return port, False
    
    def scan_ports(self, host, ports=None):
        """Scan meerdere poorten met threading"""
        if ports is None:
            ports = list(COMMON_PORTS.keys())[:1000]  # Eerste 1000 poorten
        
        self.results = {}
        
        with ThreadPoolExecutor(max_workers=self.max_workers) as executor:
            futures = {executor.submit(self.scan_port, host, port): port for port in ports}
            
            for future in as_completed(futures):
                port, is_open = future.result()
                self.results[port] = {
                    'open': is_open,
                    'service': COMMON_PORTS.get(port, f'Port-{port}')
                }
        
        return self.results
    
    def get_open_ports(self):
        """Geef alleen open poorten terug"""
        return {port: data for port, data in self.results.items() if data['open']}
    
    def get_summary(self):
        """Geef een samenvatting"""
        open_ports = self.get_open_ports()
        return {
            'total_scanned': len(self.results),
            'open_count': len(open_ports),
            'open_ports': open_ports
        }

